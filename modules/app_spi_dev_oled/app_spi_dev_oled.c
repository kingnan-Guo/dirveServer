 /** main /dev/spidevB.D <DC_Pin_number> */
int app_spi_oled_dev_init(int argc, char *argv[]){

    if(argc != 2){
        // printf(stderr, "Usage: %s  /dev/spidevB.D   <DC_pin_number> \n", argv[0]);
        return -1;
    }

    fd = open(argv[1], O_RDWR);
    if(fd < 0){
        perror("open error");
        return -1;
    }


    ioctl(fd, OLED_IOC_INIT, 0); // 初始化 OLED

    OLED_DIsp_Clear_dev();
    // 显示测试内容
    OLED_DIsp_Test_dev();
    // SPI 初始化代码可以在这里添加
    close(fd);
    return 0;
}


void app_spi_dev_oled_main(int argc, char *argv[]){

    app_spi_oled_dev_init(argc, argv);
};