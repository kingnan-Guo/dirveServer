static void set_pixel_1bpp(unsigned char *fbp, int x, int y, int screen_width_bytes, int value) {
    int byte_index = y * screen_width_bytes + (x / 8);
    unsigned char mask = 1 << (7 - (x % 8)); // MSB first
    if (value)
        fbp[byte_index] |= mask;
    else
        fbp[byte_index] &= ~mask;
}

static char *find_framebuffer_device() {
    glob_t glob_result;
    if (glob("/dev/fb*", 0, NULL, &glob_result) == 0) {
        if (glob_result.gl_pathc > 0) {
            char *device = strdup(glob_result.gl_pathv[0]);
            globfree(&glob_result);
            return device;
        }
        globfree(&glob_result);
    }
    return strdup("/dev/fb0");
}


