static void set_pixel_1bpp(unsigned char *fbp, int x, int y, int screen_width_bytes, int value) {
    int byte_index = y * screen_width_bytes + (x / 8);
    unsigned char mask = 1 << (7 - (x % 8)); // MSB first
    if (value)
        fbp[byte_index] |= mask;
    else
        fbp[byte_index] &= ~mask;
}

static char *find_framebuffer_device() {
    glob_t glob_result;
    if (glob("/dev/fb*", 0, NULL, &glob_result) == 0) {
        if (glob_result.gl_pathc > 0) {
            char *device = strdup(glob_result.gl_pathv[0]);
            globfree(&glob_result);
            return device;
        }
        globfree(&glob_result);
    }
    return strdup("/dev/fb0");
}


int app_ssd1306fb_init(int argc, char *argv[]) {


    if (argc != 2) {
        fprintf(stderr, "用法: %s \"要显示的文本\"\n", argv[0]);
        return 1;
    }
    const char *text = argv[1];

    char *fb_device = find_framebuffer_device();
    int fbfd = open(fb_device, O_RDWR);
    if (fbfd < 0) {
        perror("无法打开帧缓冲设备");
        free(fb_device);
        return 1;
    }
    printf("使用帧缓冲设备：%s\n", fb_device);
    free(fb_device);

    struct fb_fix_screeninfo finfo;
    if (ioctl(fbfd, FBIOGET_FSCREENINFO, &finfo)) {
        perror("获取固定屏幕信息失败");
        close(fbfd);
        return 1;
    }
    struct fb_var_screeninfo vinfo;
    if (ioctl(fbfd, FBIOGET_VSCREENINFO, &vinfo)) {
        perror("获取可变屏幕信息失败");
        close(fbfd);
        return 1;
    }

    printf("分辨率：%dx%d，色深：%d，行长度：%d，缓冲区大小：%ld\n",
           vinfo.xres, vinfo.yres, vinfo.bits_per_pixel, finfo.line_length, finfo.smem_len);

    if (vinfo.bits_per_pixel != 1) {
        fprintf(stderr, "不支持的色深：%d，期望 1\n", vinfo.bits_per_pixel);
        close(fbfd);
        return 1;
    }

    int width = vinfo.xres;
    int height = vinfo.yres;
    int bytes_per_line = finfo.line_length;
    size_t screensize = finfo.smem_len;

    unsigned char *fbp = mmap(NULL, screensize, PROT_READ | PROT_WRITE, MAP_SHARED, fbfd, 0);
    if (fbp == MAP_FAILED) {
        perror("映射帧缓冲失败");
        close(fbfd);
        return 1;
    }

    // 清屏测试
    memset(fbp, 0, screensize);
    if (msync(fbp, screensize, MS_SYNC) < 0) {
        perror("清屏同步失败");
    }
    printf("已清屏，检查屏幕是否变黑\n");
    sleep(2);

    // 全屏点亮测试
    memset(fbp, 0xFF, screensize);
    if (msync(fbp, screensize, MS_SYNC) < 0) {
        perror("全屏点亮同步失败");
    }
    printf("已全屏点亮，检查屏幕是否变白\n");
    sleep(2);

    // 清屏
    memset(fbp, 0, screensize);
    if (msync(fbp, screensize, MS_SYNC) < 0) {
        perror("清屏同步失败");
    }

    // 渲染文本
    int max_cols = width / 8;
    int max_rows = height / 8;
    int len = strlen(text);
    for (int i = 0; i < len; i++) {
        int col = (i % max_cols);
        int row = (i / max_cols);
        if (row >= max_rows) break;
        char c = text[i];
        if (c < 32 || c > 126) continue;
        const unsigned char *bitmap = font8x8_basic[c - 32];
        for (int cy = 0; cy < 8; cy++) {
            for (int cx = 0; cx < 8; cx++) {
                if (bitmap[cy] & (1 << (7 - cx))) {
                    set_pixel_1bpp(fbp, col * 8 + cx, row * 8 + cy, bytes_per_line, 1);
                }
            }
        }
    }

    // 同步缓冲区
    if (msync(fbp, screensize, MS_SYNC) < 0) {
        perror("文本同步失败");
    }
    printf("已写入文本：%s\n", text);

    // 调试：打印部分缓冲区数据
    printf("缓冲区前16字节：");
    for (int i = 0; i < 16; i++) {
        printf("%02x ", fbp[i]);
    }
    printf("\n");

    munmap(fbp, screensize);
    close(fbfd);
    


    

    return 0;
}


void app_ssd1306fb_main(int argc, char *argv[]){
    app_ssd1306fb_init(argc, argv);
}